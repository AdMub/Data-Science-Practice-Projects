def generate_text(prompt):
    inputs = tokenizer.encode(prompt, return_tensors="pt")
    outputs = model.generate(
        inputs,
        max_length=100,
        temperature=0.7,
        top_p=0.9,
        do_sample=True
    )
    text = tokenizer.decode(outputs[0], skip_special_tokens=True)
    return text

"""### **Creating Gradio Interface and Launching**"""

# Gradio UI
gr.Interface(
    fn=generate_text,
    inputs=gr.Textbox(lines=2, placeholder="Type a sentence..."),
    outputs=gr.Textbox(),
    title="GPT-2",
    description=(
        "OpenAI's GPT-2 is an unsupervised language model that can generate coherent text. "
        "Type a sentence and see how it continues it."
    )
).launch()